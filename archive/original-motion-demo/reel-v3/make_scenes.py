"""Reel v3: make one HyperFrames render project per scene (hyperframes/reel-<scene>/), each rendering its
graphic shots back to back at 1080×1920 through a camera (scenes/<scene>/strip.json from build_shots.py).

  python make_scenes.py [scene …]

Each project is a copy of the approved web-cut part with: the page at 1080×1920; #film wrapped in
#reelcam (the camera: a window of the 1440×1000 scene fitted to the shot's box); the caption layer
hidden; and src/shot.js driving the scene's own renderAt (scene time per shot, linear) in place of the
web cut's caption stream. SPLIT shots fit their window to the top 1080×1000; the reel uses that part.
"""
import json, re, shutil, sys
from pathlib import Path

HERE = Path(__file__).parent
HF = HERE.parent / 'hyperframes'
# scene → (web part, module exporting the scene's render, its export name)
SOURCES = {
    'opening': ('web-opening', 'pilot.js', 'renderAt'),
    's2': ('web-s2', 'scene.js', 'renderAt'),
    's3': ('web-s3', 'scene.js', 'renderAt'),
    'tab': ('web-tab', 'web.js', 'renderWeb'),
    's4': ('web-s4', 'scene.js', 'renderAt'),
    's5': ('web-s5', 'scene.js', 'renderAt'),
    's6': ('web-s6', 'scene.js', 'renderAt'),
    's7': ('web-s7', 'scene.js', 'renderAt'),
    's8': ('web-s8', 'scene.js', 'renderAt'),
    's9': ('web-s9', 'scene.js', 'renderAt'),
    's10': ('web-s10', 'scene.js', 'renderAt'),
}

NATIVE = set()  # scenes to render at 1440×1000 for the assembly to crop (none needed)

SHOT_JS = r"""/* Reel v3 render strip for scene "%(scene)s" (generated by reel-v3/make_scenes.py; plan reel-v3-plan.md §5).
 * Each segment is one shot: scene time runs linearly over it while the camera eases from one window of
 * the 1440×1000 scene to another, fitted to the shot's box (GRAPHIC 1080×1920, SPLIT the top 1080×1000).
 */
import { %(export)s as renderScene } from './%(module)s';
%(hearing_import)s
const STRIP = %(strip)s;
const gsap = window.gsap;
const EZ = gsap.parseEase('power2.inOut');
const lerp = (a, b, u) => a + (b - a) * u;
const cam = document.getElementById('reelcam');
const tag = document.getElementById('reeltag');
%(hearing_setup)s
const win = (c, box) => (c === 'fit' ? [720, 500, 1440] : c);
function renderFrame(f) {
  const seg = STRIP.segments.find((s) => f >= s.f0 && f < s.f0 + s.frames) ?? STRIP.segments.at(-1);
  const u = Math.min(1, Math.max(0, (f - seg.f0) / Math.max(1, seg.frames - 1)));
  const T = lerp(seg.reel[0], seg.reel[1], u);
  renderScene(T);
  if (tag) { // the brand card's tag rises in under the wordmark
    const k = Math.min(1, Math.max(0, (T - 61.4) / 0.5)), e = gsap.parseEase('expo.out')(k);
    tag.style.opacity = Math.min(1, k * 2).toFixed(3); tag.style.transform = `translateY(${(24 * (1 - e)).toFixed(1)}px)`;
  }
%(hearing_paint)s
  const [bx, by, bw, bh] = seg.box;
  const [c0, c1] = seg.cam ?? ['fit', 'fit'];
  const a = win(c0), b = win(c1), e = EZ(u);
  const cx = lerp(a[0], b[0], e), cy = lerp(a[1], b[1], e), w = lerp(a[2], b[2], e), s = bw / w;
  if (STRIP.native) return;
  cam.style.transform = `translate(${(bx + bw / 2 - cx * s).toFixed(2)}px, ${(by + bh / 2 - cy * s).toFixed(2)}px) scale(${s.toFixed(5)})`;
}
const clock = { f: 0 };
const N = STRIP.frames;
const tl = gsap.timeline({ paused: true });
tl.to(clock, { f: N, duration: N / 30, ease: 'none', onUpdate: () => renderFrame(Math.min(N - 1, Math.floor(clock.f + 1e-6))) }, 0);
renderFrame(0);
export const timeline = tl;
"""

def make(scene):
    part, module, export = SOURCES[scene]
    strip = json.load(open(HERE / 'scenes' / scene / 'strip.json'))
    dst = HF / f'reel-{scene}'
    if dst.exists(): shutil.rmtree(dst)
    shutil.copytree(HF / part, dst)
    src = (dst / 'src' / module)
    if export == 'renderWeb':  # the Tabular review keeps its render in web.js
        s = src.read_text(encoding='utf8'); s = s.replace('\nfunction renderWeb(t) {', '\nexport function renderWeb(t) {', 1); src.write_text(s, encoding='utf8')
    hearing = scene == 's8'
    if hearing: shutil.copy(HERE / 'lib' / 'hearing.js', dst / 'src' / 'hearing.js')
    js = SHOT_JS % {
        'scene': scene, 'export': export, 'module': module, 'strip': json.dumps({**strip, 'native': scene in NATIVE}),
        'hearing_import': "import { setupHearing } from './hearing.js';" if hearing else '',
        'hearing_setup': "renderScene(51.0);\nconst paintHearing = setupHearing(); // the extended states, on each shot's own clock" if hearing else '',
        'hearing_paint': "  if (seg.extra?.phase != null) paintHearing(seg.extra.phase, (f - seg.f0) / 30);" if hearing else '',
    }
    (dst / 'src' / 'shot.js').write_text(js, encoding='utf8')
    h = (dst / 'index.html').read_text(encoding='utf8')
    dur = round(strip['frames'] / 30, 4)
    native = scene in NATIVE
    if not native: h = h.replace('content="width=1440, height=1000"', 'content="width=1080, height=1920"')
    if scene == 's9':  # the office footage plays at its own speed: one 1:1 segment, so the clip's media time follows scene time
        assert len(strip['segments']) == 1 and abs((strip['segments'][0]['reel'][1] - strip['segments'][0]['reel'][0]) * 30 - strip['frames']) < 2
        h = re.sub(r'(<video id="lawyer" class="clip" data-start="0")\s+data-duration="[0-9.]+" data-media-start="[0-9.]+"',
                   lambda m: f'{m.group(1)} data-duration="{dur}" data-media-start="{strip["segments"][0]["reel"][0] - 48.30:.4f}"', h, 1)
    W, H = (1440, 1000) if native else (1080, 1920)
    h = re.sub(r'data-composition-id="[^"]+" data-start="0" data-width="1440" data-height="1000" data-fps="30" data-duration="[0-9.]+"',
               f'data-composition-id="reel-{scene}" data-start="0" data-width="{W}" data-height="{H}" data-fps="30" data-duration="{dur}"', h, 1)
    h = h.replace('<div class="layer" id="film">', '<div id="reelcam"><div class="layer" id="film">', 1)
    h = h.replace('    <div class="layer" id="captions"></div>', '    </div>\n    <div class="layer" id="captions"></div>', 1)
    h = h.replace('</style>', '  #reelcam { position: absolute; left: 0; top: 0; width: 1440px; height: 1000px; transform-origin: 0 0; }\n'
                  '  #captions { display: none !important; }\n' + ('' if scene == 's9' else '  #lawyer { display: none !important; }\n')
                  # the brand card's window is taller than the scene: paper all round, no edge vignette
                  + ('  #film { overflow: visible; }\n  #paper { background: none; overflow: visible; isolation: isolate; }\n'
                     '  #paper::before { content: ""; position: absolute; left: -400px; top: -600px; width: 2240px; height: 2200px; z-index: -1;'
                     ' background: #efebe3 url(assets/textures/paper.jpg) center / cover; }\n  #vignette { display: none; }\n' if scene == 's10' else '') + '  </style>', 1)
    h = re.sub(r"import \{ timeline \} from './src/web\.js';\s*window\.__timelines\['[^']+'\] = timeline;",
               f"import {{ timeline }} from './src/shot.js';\n    window.__timelines['reel-{scene}'] = timeline;", h, 1)
    assert "src/shot.js" in h and 'id="reelcam"' in h and f'reel-{scene}' in h, scene
    if scene == 's10':  # the tag under the wordmark (Figtree, the reel's caption face)
        h = h.replace('<div class="wordmark" id="wordmark">Law<em>Vriksh</em></div>', '<div class="wordmark" id="wordmark">Law<em>Vriksh</em></div>\n      <div id="reeltag" style="position:absolute; left:0; top:712px; width:1440px; text-align:center; font-family:Figtree, sans-serif; font-weight:600; font-size:40px; letter-spacing:0.01em; color:#4a3b30; opacity:0">Built for Indian lawyers</div>', 1)
        assert 'reeltag' in h
    (dst / 'index.html').write_text(h, encoding='utf8')
    hj = dst / 'hyperframes.json'
    if hj.exists(): hj.write_text(hj.read_text(encoding='utf8').replace(f'"{part}"', f'"reel-{scene}"'), encoding='utf8')
    print(f'reel-{scene}: {strip["frames"]} frames, {len(strip["segments"])} shots')

for sc in (sys.argv[1:] or [s for s in SOURCES if (HERE / 'scenes' / s / 'strip.json').exists()]):
    make(sc)
